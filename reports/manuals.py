def roles_for(user):
    """能看哪几份手册：最高权限看三份，组长看组长和组员两份，其他人看组员手册。第一份是默认。"""
    from . import access
    if access.is_super(user):
        return ['super', 'leader', 'member']
    if access.led_group_ids(user):
        return ['leader', 'member']
    return ['member']


def get(role, url):
    """把 {url} 换成网站地址，返回 {'title', 'intro', 'sections': [(标题, [(种类, 内容)])]}。"""
    fill = lambda value: [text.replace('{url}', url) for text in value] if isinstance(value, list) else value.replace('{url}', url)
    manual = MANUALS[role]
    return {'title': manual['title'], 'intro': manual['intro'],
            'sections': [(title, [(kind, fill(value)) for kind, value in blocks]) for title, blocks in manual['sections']]}


def to_docx(role, url):
    """Word 版（可打印、发群里）。字体用微软雅黑，没有时 Word 会自动替换。"""
    manual = get(role, url)
    document = Document()
    for name in ('Normal', 'Title', 'Heading 1', 'Heading 2', 'List Bullet'):
        style = document.styles[name]
        # 模板里标题样式带“主题字体”属性，会盖过这里设的字体，导致同一行中英文混用两种字体；先清掉再统一设置
        fonts = style.element.get_or_add_rPr().get_or_add_rFonts()
        fonts.attrib.clear()
        for attribute in ('ascii', 'hAnsi', 'eastAsia', 'cs'):
            fonts.set(qn(f'w:{attribute}'), 'Microsoft YaHei')
        if name != 'Normal':
            style.font.color.rgb = RGBColor.from_string('20384D')
    document.styles['Normal'].font.size = Pt(11)
    document.add_heading(manual['title'], level=0)
    document.add_paragraph(manual['intro'])
    document.add_paragraph(f'网址：{url}')
    for number, (title, blocks) in enumerate(manual['sections'], start=1):
        document.add_heading(f'{number}. {title}', level=1)
        for kind, value in blocks:
            if kind == 'p':
                document.add_paragraph(value)
            elif kind == 'h':
                document.add_heading(value, level=2)
            elif kind == 'steps':
                for index, text in enumerate(value, start=1):
                    paragraph = document.add_paragraph(f'{index}. {text}')
                    paragraph.paragraph_format.left_indent = Pt(18)
                    paragraph.paragraph_format.first_line_indent = Pt(-14)
            elif kind == 'list':
                for text in value:
                    document.add_paragraph(text, style='List Bullet')
            elif kind == 'tip':
                paragraph = document.add_paragraph()
                paragraph.add_run('提示：').bold = True
                paragraph.add_run(value)
    stream = BytesIO()
    document.save(stream)
    return stream.getvalue()
